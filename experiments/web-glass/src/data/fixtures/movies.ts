export const movies: Movie[] = movieDefs.map((d) => {
  const poster = art.poster(d.id);
  const backdrop = art.backdrop(d.id);
  const hasLogo = !d.commons || !!d.commons.logo;
  const writers = d.writers ?? [d.director];
  return {
    id: d.id,
    kind: 'movie',
    libraryId: 'lib-movies',
    title: d.title,
    sortTitle: d.title.replace(/^(The|A|An) /, ''),
    year: d.year,
    released: `${d.year}-${String(((d.id.length * 7) % 12) + 1).padStart(2, '0')}-${String(((d.id.length * 13) % 27) + 1).padStart(2, '0')}`,
    runtime: d.runtime,
    contentRating: d.rating,
    genres: d.genres,
    tagline: d.tagline,
    summary: d.summary,
    studio: d.studio,
    country: d.country ?? 'United States',
    originalLanguage: d.lang ?? 'en',
    ratings: { critic: d.critic, audience: d.audience },
    cast: castList(d.cast),
    crew: crewList([['Director', d.director], ...writers.map((w) => ['Writer', w] as [string, string])]),
    versions: versionsFor(d.id, d.quality, d.runtime, d.lang),
    chapters: numberedChapters(d.runtime, d.chapters),
    extras: (d.extras ?? []).map(([title, kind, runtime], i) => ({ id: `${d.id}-x${i}`, title, kind, runtime, thumb: backdrop })),
    collectionIds: d.collections ?? [],
    art: { poster, backdrop, logo: hasLogo ? art.logo(d.id) : undefined },
    palette: paletteFor(poster),
    addedAt: daysAgo(d.added, 9 + (d.id.length % 12)),
    source: d.source ?? GEN,
    streamId: d.stream ?? (d.runtime > 60 ? 'coffee-run' : 'sintel-trailer'),
  };
});

