#!/usr/bin/env python3
"""Builds the web artwork set from the Portico Classic app's licensed artwork.

Sources: experiments/classic/assets/art (see experiments/classic/scripts/art for where each
picture comes from: Wikimedia Commons public-domain posters and stills, Blender Foundation
open movies (CC BY), picsum.photos (Unsplash) and generated art).

Output:
  public/art/<kind>/<id>.webp          web sizes, WebP
  src/data/fixtures/art.generated.ts   which ids have art, plus tints and real-photo people

Run: npm run art
"""
import json
import os
import re
import sys
from concurrent.futures import ThreadPoolExecutor

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '..', 'classic', 'assets', 'art')
CLASSIC_MANIFEST = os.path.join(ROOT, '..', 'classic', 'src', 'data', 'fixtures', 'art.generated.ts')
OUT = os.path.join(ROOT, 'public', 'art')
MANIFEST = os.path.join(ROOT, 'src', 'data', 'fixtures', 'art.generated.ts')

# kind: (max width, quality). Sources are already close to display size; this mostly re-encodes.
KINDS = {
    'posters': (360, 78),
    'backdrops': (1280, 70),
    'stills': (480, 74),
    'people': (300, 78),
    'albums': (400, 78),
    'artists': (400, 78),
    'books': (360, 78),
    'logos': (240, 90),
    'photos': (1600, 72),
    'photothumbs': (360, 74),
}


def unletterbox(im):
    """Crops black letterbox bars (and anything below the lower bar, such as a captured player's
    controls) from backdrops, then trims to 16:9 so the picture fills a wide frame."""
    g = im.convert('L')
    w, h = g.size
    # A letterbox row is uniformly black: even its brightest pixel is dark (a starry sky is not).
    rows = [max(g.crop((0, y, w, y + 1)).getdata()) for y in range(h)]
    top = next((y for y, v in enumerate(rows) if v > 40), 0)
    if top < h * 0.04:
        return im
    bottom = next((y for y in range(top + h // 2, h) if rows[y] < 30), h)
    im = im.crop((0, top, w, bottom))
    target_w = round(im.height * 16 / 9)
    if target_w < w:
        left = (w - target_w) // 2
        im = im.crop((left, 0, left + target_w, im.height))
    return im


def convert(kind, name):
    src = os.path.join(SRC, kind, name)
    ident = os.path.splitext(name)[0]
    dst = os.path.join(OUT, kind, ident + '.webp')
    if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
        return ident
    width, quality = KINDS[kind]
    im = Image.open(src)
    im = im.convert('RGBA' if kind == 'logos' else 'RGB')
    if kind == 'backdrops':
        im = unletterbox(im)
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    im.save(dst, 'WEBP', quality=quality, method=6)
    return ident


def main():
    ids = {}
    with ThreadPoolExecutor(max_workers=8) as pool:
        for kind in KINDS:
            os.makedirs(os.path.join(OUT, kind), exist_ok=True)
            names = sorted(n for n in os.listdir(os.path.join(SRC, kind)) if re.search(r'\.(jpe?g|png)$', n, re.I))
            ids[kind] = sorted(pool.map(lambda n, k=kind: convert(k, n), names))
            print(f'{kind}: {len(ids[kind])}', file=sys.stderr)
    classic = open(CLASSIC_MANIFEST, encoding='utf-8').read()
    tints = json.loads(re.search(r'export const tints: Record<string, string> = (\{.*?\});', classic, re.S).group(1))
    real = json.loads(re.search(r'export const realPhotoPeople = new Set<string>\((\[.*?\])\);', classic, re.S).group(1))
    lines = ['/* Generated by scripts/art.py. Do not edit. */', '']
    for kind, values in ids.items():
        lines.append(f'export const {kind} = new Set<string>({json.dumps(values)});')
    lines.append(f'export const tints: Record<string, string> = {json.dumps(tints)};')
    lines.append(f'export const realPhotoPeople = new Set<string>({json.dumps(real)});')
    open(MANIFEST, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
