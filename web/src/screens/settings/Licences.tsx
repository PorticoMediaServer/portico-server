import React, {useEffect, useMemo, useState} from 'react';
import {Link, useNavigate} from '@tanstack/react-router';
import {licenceCount, licenceDetail, licenceRowDetail, licenceSections, licenceSourceRows, parseLicenceData, type LicenceData} from '@core/presentation/index.ts';
import {useI18n} from '../../app/i18n';
import {Icon, KeyValue, Loading, Notice, SettingsGroup, SettingsRow, Text} from '../../ui';
import s from './Settings.module.css';

/**
 * Settings › About › Open-source licenses: Portico's own licence and where its source is
 * published, then every component the web app and the server are built from, each opening its
 * copyright lines and full licence text. The list (`src/generated/licences.json`, generated by
 * `web/scripts/licences.ts`) is large, so it is fetched only when this page opens.
 */
export function Licences({id}: {id?: string}) {
  const {t} = useI18n();
  const [data, setData] = useState<LicenceData | null>();
  useEffect(() => {
    let live = true;
    import('../../generated/licences.json').then(m => { if (live) setData(parseLicenceData(m.default) ?? null); }, () => { if (live) setData(null); });
    return () => { live = false; };
  }, []);
  if (data === undefined) return <Loading label={t('licenses.loading')} />;
  if (data === null) return <Notice tone="error">{t('licenses.unavailable')}</Notice>;
  return id ? <LicenceView data={data} id={id} /> : <LicenceList data={data} />;
}

const open = (url: string) => window.open(url, '_blank', 'noopener');

export function LicenceList({data}: {data: LicenceData}) {
  const {t} = useI18n();
  const navigate = useNavigate();
  const show = (id: string) => void navigate({to: '/settings/$section', params: {section: 'about'}, search: {tab: 'licenses', id}});
  const sections = useMemo(() => licenceSections(data), [data]);
  const portico = sections.find(x => x.group === 'portico')?.components[0];
  return (
    <div className={s.page}>
      <div>
        <Link to="/settings/$section" params={{section: 'about'}} search={{}} className={s.back}><Icon name="back" size={14} />{t('settings.about')}</Link>
        <header className={s.head}><h1 className={s.title}>{t('licenses.title')}</h1></header>
      </div>
      <SettingsGroup title={t('licenses.section.portico')} description={t('licenses.portico.body')}>
        {portico ? <SettingsRow label={portico.name} help={portico.licence} onClick={() => show(portico.id)} /> : null}
      </SettingsGroup>
      <SettingsGroup title={t('licenses.source.title')}>
        {licenceSourceRows(data).map(row => <SettingsRow key={row.id} icon="external" label={t(row.label)} help={row.url} onClick={() => open(row.url)} />)}
      </SettingsGroup>
      <Text as="p" variant="caption" tone="tertiary">{t('licenses.count', {count: licenceCount(data)})}</Text>
      {sections.filter(x => x.group !== 'portico').map(section => (
        <SettingsGroup key={section.group} title={t(section.title)}>
          {section.components.map(c => <SettingsRow key={c.id} label={c.name} help={licenceRowDetail(c)} onClick={() => show(c.id)} />)}
        </SettingsGroup>
      ))}
    </div>
  );
}

export function LicenceView({data, id}: {data: LicenceData; id: string}) {
  const {t} = useI18n();
  const detail = licenceDetail(data, id);
  const back = <Link to="/settings/$section" params={{section: 'about'}} search={{tab: 'licenses'}} className={s.back}><Icon name="back" size={14} />{t('licenses.title')}</Link>;
  if (!detail) return <div className={s.page}><div>{back}</div><Notice tone="warning">{t('licenses.notFound')}</Notice></div>;
  const {component, copyright, text} = detail;
  const rows: [React.ReactNode, React.ReactNode][] = [
    ...(component.version ? [[t('licenses.version'), component.version] as [string, string]] : []),
    [t('licenses.license'), component.licence],
    ...(component.url ? [[t('licenses.website'), <a key="url" href={component.url} target="_blank" rel="noopener noreferrer">{component.url}</a>] as [string, React.ReactNode]] : []),
  ];
  return (
    <div className={s.page}>
      <div>
        {back}
        <header className={s.head}><h1 className={s.title}>{component.name}</h1></header>
      </div>
      <KeyValue rows={rows} />
      {copyright.length ? (
        <SettingsGroup title={t('licenses.copyright')}>
          <div className={s.licenceCopyright}>{copyright.map(line => <p key={line}>{line}</p>)}</div>
        </SettingsGroup>
      ) : null}
      <SettingsGroup title={t('licenses.text')}>
        {text ? <pre className={s.licenceText} tabIndex={0}>{text}</pre> : <p className={s.sectionLede}>{t(component.textAtUrl ? 'licenses.textAtWebsite' : 'licenses.textMissing')}</p>}
      </SettingsGroup>
    </div>
  );
}
