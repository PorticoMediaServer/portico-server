// routeScopes says what an API key or personal access token must have been
// given to use each hand-registered route. Routes on the typed registry declare
// theirs where they are registered (apikit.Metadata.Requires); this table is
// the same decision for the routes that have not moved there yet, and each
// entry moves with its route.
//
// It is exhaustive in the way routeLanes is: a test walks the routes the
// package registers and fails when one is missing. It also fails safe. A route
// this table does not name is refused to every key and token, so a route added
// without a decision is closed to credentials rather than open to them.
//
// The scopes are apikit's. Three rules decided the entries:
//
//   - Anything that signs someone in or out, changes a password or a second
//     factor, switches profile, approves or links a device, or takes part in
//     claiming the server is session-only. A credential can never mint, widen
//     or outlive-by-proxy another credential.
//   - Reading what a member can see is "read"; playing, and changing the
//     member's own state, lists, preferences and recordings, is "playback";
//     scanning, matching, editing and deleting what is in the libraries is
//     "library"; the rest of administration is "admin".
//   - A scope never replaces the role check a handler makes. A member's token
//     with the admin scope is still a member.
