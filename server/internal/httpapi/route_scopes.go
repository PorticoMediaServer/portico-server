// legacyRouteScope is the scope of a hand-registered mux pattern. A pattern the
// table does not name is session-only.
func legacyRouteScope(pattern string) apikit.Scope {
	if scope, ok := routeScopes[pattern]; ok {
		return scope
	}
	return apikit.ScopeSession
}
